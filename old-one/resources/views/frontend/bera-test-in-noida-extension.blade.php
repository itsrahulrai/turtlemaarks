                                <h2 class="margin-bottom-20 audiologist-subtitle">Exactly What Is BERA Testing?</h2>
                                <p class="margin-bottom-20">
                                    BERA means Brainstem Evoked Response Audiometry. Simply put, it evaluates the brain's response to sounds using electrical activity within the auditory nerves, starting from the ears to the brain stem. Unlike any other hearing test, this one does not require a response from the patient in any way, which is why it is considered the best one to conduct hearing tests on babies and infants.
                                </p>
                                <p class="margin-bottom-20">Some facts about the test:</p>
                                <ul class="single-list">
                                    <li class="amount">• It is totally painless and non-invasive.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• Electrodes, similar to stickers, are placed on the scalp and ear lobes.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• Soft clicking sounds are played through tiny earphones.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• The baby is usually asleep or resting calmly throughout.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• No injections, no discomfort, and no radiation involved.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• Results give a clear, objective picture of hearing nerve function.</li>
