                                <h2 class="margin-bottom-20 audiologist-subtitle">Understanding Your Audiogram</h2>
                                <p class="margin-bottom-20">
                                    The question we get most often is, "What does this graph even mean?" Here is an easy point-based explanation:
                                </p>
                                <ul class="single-list">
                                    <li class="amount">• The horizontal axis shows pitch, from low to high frequencies.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• The vertical axis shows volume, from very soft to very loud.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• Your results are plotted as points, showing the softest sound you can hear at each pitch.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• Higher values on the graph correspond to good hearing ability, whereas the lower values denote hearing problems.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• These are categorized either as normal hearing, mild hearing loss, moderate hearing loss, severe hearing loss, or profound hearing loss.</li>
                                </ul>
                                <ul class="single-list">
                                    <li class="amount">• Each ear is tested and plotted separately for accuracy.</li>
                                </ul>
                                <p class="margin-top-20">
                                    We never just hand you a report and send you off — every audiogram from our clinic comes with a proper explanation of what it means for your daily life.
